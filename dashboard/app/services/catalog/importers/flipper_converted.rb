module Catalog
  module Importers
    # Flipper-IRDB's `_Converted_` folder: ~6,900 remotes converted from older databases (LIRC, irdb, Pronto, ...).
    # Unlike the curated folders it has no category directories, so the category is inferred from device-type
    # keywords. Everything it creates is tagged source "flipper_converted" (and ranks below curated remotes), so it
    # can be reviewed or removed on its own:  RemoteConfig.where(source: "flipper_converted").destroy_all
    #
    #   Catalog::Importers::FlipperConverted.new("/path/to/Flipper-IRDB").call
    class FlipperConverted < FlipperIrdb
      SUBFOLDERS = %w[CSV IR_Plus Pronto Other].freeze

      def call
        Categories.seed!
        SUBFOLDERS.each do |sub|
          next if @only && !@only.include?(sub)

          dir = @root.join("_Converted_", sub)
          next unless dir.directory?

          Dir.glob(dir.join("**/*.ir")).sort.each do |file|
            path = Pathname(file)
            _brand, model = names_for(path, nil)
            slug = category_slug_for(path, model) || category_from_buttons(path) || "other"
            import_file(path, DeviceCategory.find_by!(slug: slug))
          end
          log "_Converted_/#{sub}: done"
        end
        stats
      end

      private

      def source_tag = "flipper_converted"
      # Below curated remotes of the same completeness: a wrong guess here should not outrank a verified one.
      def popularity_for(keys) = keys.count { |k| ButtonNames.canonical?(k) } / 2

      # CSV/<A-Z>/<Brand>/<DeviceType>/<code>.ir      IR_Plus|Pronto/<A-Z>/<Brand>/<Model>.ir      Other/<Brand>/<Model>.ir
      def parts_for(path)
        parts = path.relative_path_from(@root.join("_Converted_")).each_filename.to_a
        kind = parts.shift
        parts.shift if kind != "Other" # the A-Z bucket
        [kind, parts]
      end

      def names_for(path, _category)
        kind, parts = parts_for(path)
        brand_dir = parts.first
        base = File.basename(path.to_s, ".ir")
        brand = tidy(brand_dir).presence || "Generic"
        model =
          if kind == "CSV" && parts.size >= 3
            "#{tidy(parts[1].sub(/\AUnknown[_-]?/i, '')).presence || 'Remote'} (code #{base})"
          else
            tidy(base.sub(/\A#{Regexp.escape(brand_dir.to_s)}[_\- ]*/i, "")).presence || "Default"
          end
        [brand, model]
      end

      def category_slug_for(path, model)
        kind, parts = parts_for(path)
        text = kind == "CSV" && parts.size >= 3 ? parts[1].tr("_-", " ") : "#{model} #{source_hint(path)}"
        CategoryGuess.from_text(text)
      end

      # IR_Plus files record their original path ("Autogenerated from ircodes/SONY (AVR)/STR-DA50ES.xml").
      def source_hint(path)
        File.foreach(path, encoding: "UTF-8", invalid: :replace, undef: :replace).first(12).filter_map { |l| l[/Autogenerated from (.+)/, 1] }.first.to_s.tr("/", " ")
      rescue StandardError
        ""
      end

      def category_from_buttons(path)
        names = path.read(encoding: "UTF-8", invalid: :replace, undef: :replace).scan(/^name:\s*(.+)$/).flatten
        CategoryGuess.from_buttons(names.map { |n| ButtonNames.normalize(n) })
      end

      def tidy(str) = str.to_s.tr("_", " ").squish
    end
  end
end
